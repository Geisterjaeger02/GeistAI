def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    n = len(LANGS)
    for row in STRINGS:
        assert len(row) == n + 1, f"{row[0]}: {len(row) - 1} translations, need {n}"
        for text in row[1:]:
            assert row[0] != "S_WELCOME" or text.count("%s") == 1, row
            assert "%" not in text or row[0] == "S_WELCOME", row[0]
    for row in THEMES:
        assert len(row) == n, f"theme {row[0]}: {len(row)} names, need {n}"
    ids = [row[0] for row in STRINGS]
    assert len(ids) == len(set(ids)), "duplicate id"

    out = ["// Generated by tools/gen_i18n.py - edit the tables there, not this file.",
           "#pragma once", "#include <stdint.h>", "", "namespace geist {", "",
           "enum UiLang : uint8_t {"]
    out += [f"  UI_{code.upper()}," for code in LANGS]
    out += ["  UI_LANG_COUNT", "};", "", "enum Str : uint16_t {"]
    out += [f"  {i}," for i in ids]
    out += ["  S_COUNT", "};", "",
            "static const char* const kStrings[UI_LANG_COUNT][S_COUNT] = {"]
    for li, code in enumerate(LANGS):
        out.append(f"    {{  // {LANG_NAMES[li]}")
        out += [f"        {c_str(row[li + 1])}," for row in STRINGS]
        out.append("    },")
    out += ["};", "", f"constexpr int THEME_NAME_COUNT = {len(THEMES)};",
            "static const char* const kThemeNames[UI_LANG_COUNT][THEME_NAME_COUNT] = {"]
    for li in range(n):
        out.append("    {" + ", ".join(c_str(t[li]) for t in THEMES) + "},")
    out += ["};", "", "static const char* const kUiLangNames[UI_LANG_COUNT] = {"]
    out.append("    " + ", ".join(c_str(x) for x in LANG_NAMES) + ",")
    out += ["};", "", "}  // namespace geist", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT.name}: {len(ids)} strings x {n} languages, {len(THEMES)} themes")


if __name__ == "__main__":
    main()
